class TestGoldenDocument:
    """The vertical slice: real scanner output through real ingest."""

    def test_golden_document_validates(self, golden_document: dict) -> None:
        validate_document(golden_document)

    def test_golden_document_ingests(self, golden_document: dict) -> None:
        result = ingest_document(
            golden_document,
            scan_target=SCAN_TARGET,
            discovered_by=ScannerKind.SOURCE,
        )
        assert result.artefact_count > 0
        assert result.gaps == [], f"unexpected gaps: {result.gaps}"

    def test_key_sizes_survive_source_to_artefact(self, golden_document: dict) -> None:
        """The message-interpolation contract, end to end.

        A key size travels: source line -> Semgrep message -> CBOM property ->
        artefact field. Any break in that chain silently degrades findings to
        NEEDS_CONTEXT, so it is asserted on real output.
        """
        result = ingest_document(golden_document, scan_target=SCAN_TARGET)
        sized = [
            a
            for a in result.artefacts
            if a.detail is not None and getattr(a.detail, "key_size_bits", None)
        ]
        assert sized, "no artefact carried a key size"
        assert any(a.detail.key_size_bits == 2048 for a in sized)

    def test_modes_survive(self, golden_document: dict) -> None:
        """R19: 'AES' alone is not an answer; AES-CBC and AES-ECB are."""
        result = ingest_document(golden_document, scan_target=SCAN_TARGET)
        modes = {
            a.detail.mode
            for a in result.artefacts
            if a.detail is not None and getattr(a.detail, "mode", None)
        }
        assert CipherMode.CBC in modes
        assert CipherMode.ECB in modes, "ECB is a finding in its own right"

    def test_every_artefact_has_verifiable_evidence(
        self, golden_document: dict
    ) -> None:
        """An unsourced finding is a bug, not a low-quality artefact."""
        result = ingest_document(golden_document, scan_target=SCAN_TARGET)
        for artefact in result.artefacts:
            assert artefact.evidence, f"{artefact.name} has no evidence"
            assert artefact.evidence[0].location.path
            assert artefact.evidence[0].location.line

    def test_tool_versions_are_recorded(self, golden_document: dict) -> None:
        result = ingest_document(golden_document, scan_target=SCAN_TARGET)
        names = {t.name for t in result.tools}
        assert "source-scanner" in names
        assert any("semgrep" in n for n in names)

    def test_ingest_is_idempotent(self, golden_document: dict) -> None:
        """Deterministic ids mean re-ingesting yields the same artefact set."""
        first = ingest_document(golden_document, scan_target=SCAN_TARGET)
        second = ingest_document(golden_document, scan_target=SCAN_TARGET)

        assert {a.artefact_id for a in first.artefacts} == {
            a.artefact_id for a in second.artefacts
        }

    def test_taint_evidence_reaches_ingest(self, golden_document: dict) -> None:
        """Mosca's X depends on this scanner-evidence tier existing."""
        categories = {
            p["value"]
            for component in golden_document["components"]
            for p in component.get("properties", [])
            if p["name"] == "trinetra:data-category"
        }
        assert categories, "no data-category property in the golden document"
